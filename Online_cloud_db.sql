DROP DATABASE IF EXISTS MAHARASHTRIAN_THALI;
CREATE DATABASE MAHARASHTRIAN_THALI;
USE MAHARASHTRIAN_THALI;

-- 1. SHOPS TABLE
CREATE TABLE SHOPS (
    SHOP_ID INT AUTO_INCREMENT PRIMARY KEY,
    SHOP_NAME VARCHAR(150) NOT NULL,
    LOCATION VARCHAR(255),
    CREATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

-- 2. SYSTEM_USERS TABLE (With auto-updating UPDATED_AT)
CREATE TABLE SYSTEM_USERS (
    USER_ID INT AUTO_INCREMENT PRIMARY KEY,
    USERNAME VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    ROLE ENUM('ADMIN', 'WAITER', 'CASHIER') NOT NULL,
    SHOP_ID INT NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    FOREIGN KEY (SHOP_ID) REFERENCES SHOPS(SHOP_ID)
);

-- 3. MENU_GROUP TABLE
CREATE TABLE MENU_GROUP (
    GROUP_ID INT AUTO_INCREMENT PRIMARY KEY,
    SHOP_ID INT NOT NULL,
    GROUP_NAME VARCHAR(100) NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (SHOP_ID) REFERENCES SHOPS(SHOP_ID)
);

-- 4. MENU TABLE (With auto-updating UPDATED_AT)
CREATE TABLE MENU (
    MENU_ID INT AUTO_INCREMENT PRIMARY KEY,
    SHOP_ID INT NOT NULL,
    GROUP_ID INT NOT NULL,
    ITEM_NAME VARCHAR(150) NOT NULL,
    PRICE DECIMAL(10,2) NOT NULL,
    UPDATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (SHOP_ID) REFERENCES SHOPS(SHOP_ID),
    FOREIGN KEY (GROUP_ID) REFERENCES MENU_GROUP(GROUP_ID),
    CONSTRAINT UNIQUE_MENU_ITEM UNIQUE (ITEM_NAME, SHOP_ID, GROUP_ID)
);

-- 5. ORDERS TABLE
CREATE TABLE ORDERS (
    ORDER_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    DEVICE_ORDER_UUID VARCHAR(100) NOT NULL UNIQUE,
    SHOP_ID INT NOT NULL,
    USER_ID INT NOT NULL,
    ORDER_TIME DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PAYMENT_TIME DATETIME(6) NULL DEFAULT NULL,
    TOTAL_AMOUNT DECIMAL(10,2) NOT NULL,
    MODE_OF_PAYMENT ENUM('CASH', 'ONLINE') NULL,
    STATUS ENUM('ACTIVE', 'PAID', 'CANCELLED') NOT NULL DEFAULT 'ACTIVE',
    SOURCE_DEVICE_ID VARCHAR(100),
    SYNC_TIME DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    FOREIGN KEY (SHOP_ID) REFERENCES SHOPS(SHOP_ID),
    FOREIGN KEY (USER_ID) REFERENCES SYSTEM_USERS(USER_ID)
);

-- 6. ORDER_ITEMS TABLE
CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ORDER_ID BIGINT NOT NULL,
    MENU_ID INT NOT NULL,
    QUANTITY INT NOT NULL,
    PRICE_AT_PURCHASE DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
    FOREIGN KEY (MENU_ID) REFERENCES MENU(MENU_ID)
);

-- 7. EXCEL_IMPORT_BATCH TABLE
CREATE TABLE EXCEL_IMPORT_BATCH (
    IMPORT_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    USER_ID INT NOT NULL,
    FILE_NAME VARCHAR(255) NOT NULL,
    TOTAL_ROWS INT NOT NULL,
    TOTAL_ORDERS INT NOT NULL,
    TOTAL_ITEMS INT NOT NULL,
    STATUS VARCHAR(50) NOT NULL,
    IMPORTED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    FOREIGN KEY (USER_ID) REFERENCES SYSTEM_USERS(USER_ID)
);

-- 8. SYNC_LOGS TABLE
CREATE TABLE SYNC_LOGS (
    LOG_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    SHOP_ID INT NOT NULL,
    ENTITY_TYPE VARCHAR(50) NOT NULL,
    ENTITY_ID BIGINT NOT NULL,
    ACTION VARCHAR(20) NOT NULL,
    SOURCE_DEVICE_ID VARCHAR(100),
    SYNC_TIMESTAMP DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    FOREIGN KEY (SHOP_ID) REFERENCES SHOPS(SHOP_ID)
);

-- 9. SYSTEM_LOGS TABLE
CREATE TABLE SYSTEM_LOGS (
    LOG_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    SHOP_ID INT,
    USER_ID INT,
    SOURCE_DEVICE_ID VARCHAR(100),
    EVENT_TYPE ENUM(
        'SYNC_ERROR',
        'API_ERROR',
        'CONNECTION_LOST',
        'DATA_INTEGRITY_ERROR',
        'AUTH_FAILED',
        'SYSTEM_CRITICAL'
    ) NOT NULL,
    MESSAGE TEXT NOT NULL,
    EVENT_TIME DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    FOREIGN KEY (SHOP_ID) REFERENCES SHOPS(SHOP_ID),
    FOREIGN KEY (USER_ID) REFERENCES SYSTEM_USERS(USER_ID)
);

